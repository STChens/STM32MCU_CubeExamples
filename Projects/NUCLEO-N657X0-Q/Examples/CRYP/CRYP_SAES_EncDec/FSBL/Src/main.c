void print_buf(char *str, uint8_t *buf, int size)
{
  int i;
  
  if(str != NULL);
  printf("%s\r\n", str);
  printf("=============================================\r\n");
  for(i=0;i<size;i++)
  {
    printf("%02x ", buf[i]);
    if((i+1)%16 == 0)
      printf("\r\n");
  }
  printf("\r\n=============================================\r\n");
}

